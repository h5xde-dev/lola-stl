// Способы оплаты, включённые в админке (для текстов). Тестовая оплата сюда не попадает.
export function payMethodNames(settings) {
  const p = mergePayments(settings?.payments);
  const modes = Array.isArray(settings?.tochka?.modes) && settings.tochka.modes.length ? settings.tochka.modes : null;
  const list = PAY_METHODS.filter(m => !m.test && p[m.id] && methodFor(m, "tochka") && (!modes || modes.includes(m.tochka)));
  return list.length ? list : PAY_METHODS.filter(m => ["sbp", "card"].includes(m.id));
}

